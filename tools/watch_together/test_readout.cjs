const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const elements = {ocrStatus: {}, ocrText: {}};
const source = fs.readFileSync(__dirname + '/app.js', 'utf8');
const scope = { $: id => elements[id], formatPosition: n => String(n) };
vm.createContext(scope);
vm.runInContext(source.slice(source.indexOf('function resetReadout'), source.indexOf('async function connect')), scope);
scope.showReadout({screenshot_subtitles: ['<script>example</script>', '第二句'], analysis_position: 20});
assert.equal(elements.ocrText.textContent, '<script>example</script>\n第二句');
assert.match(elements.ocrStatus.textContent, /20.*已识别/);
scope.showReadout({screenshot_subtitles: [], analysis_position: 30});
assert.equal(elements.ocrText.textContent, '');
assert.match(elements.ocrStatus.textContent, /未读到清晰字幕/);
scope.showReadout({});
assert.match(elements.ocrStatus.textContent, /未返回识别结果/);
scope.resetReadout();
assert.equal(elements.ocrText.textContent, '');
assert.match(elements.ocrStatus.textContent, /等待/);
console.log('Subtitle readout states passed');
